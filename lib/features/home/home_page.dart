  List<ChatHistoryItem> get _filteredHistory {
    final query = _historySearch.trim().toLowerCase();
    return _historyItems.where((item) {
      final folderMatch = _selectedFolder == 'All' || item.folder == _selectedFolder;
      final textMatch = query.isEmpty ||
          item.title.toLowerCase().contains(query) ||
          item.preview.toLowerCase().contains(query);
      return folderMatch && textMatch;
    }).toList();
  }

  Future<void> _createFolder() async {
    final controller = TextEditingController();

    final name = await showDialog<String>(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: AppTheme.surface,
        title: const Text(
          'Create Folder',
          style: TextStyle(color: AppTheme.textPrimary),
        ),
        content: TextField(
          controller: controller,
          autofocus: true,
          style: const TextStyle(color: AppTheme.textPrimary),
          decoration: const InputDecoration(
            hintText: 'Folder name',
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, controller.text.trim()),
            child: const Text('Create'),
          ),
        ],
      ),
    );

    controller.dispose();

    if (name == null || name.trim().isEmpty) {
      return;
    }

    await ChatHistoryService.createFolder(name);

    if (!mounted) {
      return;
    }

    await _loadFolders();

    setState(() {
      _selectedFolder = name.trim();
    });
  }

  Future<void> _renameChat(ChatHistoryItem item) async {
    final controller = TextEditingController(text: item.title);

    final newTitle = await showDialog<String>(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: AppTheme.surface,
        title: const Text(
          'Rename Chat',
          style: TextStyle(color: AppTheme.textPrimary),
        ),
        content: TextField(
          controller: controller,
          autofocus: true,
          style: const TextStyle(color: AppTheme.textPrimary),
          decoration: const InputDecoration(
            hintText: 'Chat name',
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, controller.text.trim()),
            child: const Text('Save'),
          ),
        ],
      ),
    );

    controller.dispose();

    if (newTitle == null || newTitle.trim().isEmpty) {
      return;
    }

    await ChatHistoryService.renameConversation(
      item.id,
      newTitle.trim(),
    );

    if (mounted) {
      await _loadHistory();
    }
  }

  Future<void> _moveChat(ChatHistoryItem item) async {
    final folders = await ChatHistoryService.getFolders();

    if (!mounted) {
      return;
    }

    final selected = await showDialog<String>(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: AppTheme.surface,
        title: const Text(
          'Move Chat',
          style: TextStyle(color: AppTheme.textPrimary),
        ),
        content: SizedBox(
          width: double.maxFinite,
          child: ListView(
            shrinkWrap: true,
            children: folders.map((folder) {
              return ListTile(
                leading: Icon(
                  folder == item.folder
                      ? Icons.radio_button_checked_rounded
                      : Icons.folder_outlined,
                  color: folder == item.folder
                      ? AppTheme.cyan
                      : AppTheme.textSecondary,
                ),
                title: Text(
                  folder,
                  style: const TextStyle(
                    color: AppTheme.textPrimary,
                  ),
                ),
                onTap: () => Navigator.pop(context, folder),
              );
            }).toList(),
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
        ],
      ),
    );

    if (selected == null || selected == item.folder) {
      return;
    }

    await ChatHistoryService.moveConversation(
      item.id,
      selected,
    );

    if (mounted) {
      await _loadHistory();
    }
  }

  Future<void> _deleteChat(ChatHistoryItem item) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: AppTheme.surface,
        title: const Text(
          'Delete Chat?',
          style: TextStyle(color: AppTheme.textPrimary),
        ),
        content: Text(
          'Delete "${item.title}" permanently?',
          style: const TextStyle(
            color: AppTheme.textSecondary,
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(context, true),
            child: const Text('Delete'),
          ),
        ],
      ),
    );

    if (confirmed != true) {
      return;
    }

    await ChatHistoryService.deleteConversation(item.id);

    if (!mounted) {
      return;
    }

    await _loadHistory();

    if (!mounted) {
      return;
    }

    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(
        content: Text('Chat deleted'),
        duration: Duration(seconds: 1),
      ),
    );
  }


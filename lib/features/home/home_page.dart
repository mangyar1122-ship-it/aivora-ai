  Future<void> _editProfile() async {
    final user = FirebaseAuth.instance.currentUser;
    final nameController = TextEditingController(text: _customName);
    final emailController = TextEditingController(text: _customEmail.isNotEmpty ? _customEmail : (user?.email ?? ''));

    final save = await showDialog<bool>(
      context: context,
      builder: (context) => AlertDialog(
        backgroundColor: AppTheme.surface,
        title: const Text('Edit Profile', style: TextStyle(color: AppTheme.textPrimary)),
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            TextField(
              controller: nameController,
              style: const TextStyle(color: AppTheme.textPrimary),
              decoration: const InputDecoration(labelText: 'Name'),
            ),
            const SizedBox(height: 14),
            TextField(
              controller: emailController,
              keyboardType: TextInputType.emailAddress,
              style: const TextStyle(color: AppTheme.textPrimary),
              decoration: const InputDecoration(labelText: 'Email'),
            ),
          ],
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(context, false), child: const Text('Cancel')),
          FilledButton(onPressed: () => Navigator.pop(context, true), child: const Text('Save')),
        ],
      ),
    );

    if (save != true) {
      nameController.dispose();
      emailController.dispose();
      return;
    }

    final newName = nameController.text.trim();
    final newEmail = emailController.text.trim();
    nameController.dispose();
    emailController.dispose();

    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('aivora_profile_name', newName);
    await prefs.setString('aivora_profile_email', newEmail);

    if (!mounted) return;
    setState(() {
      _customName = newName;
      _customEmail = newEmail;
    });

    if (user != null && newEmail.isNotEmpty && newEmail != user.email) {
      try {
        await user.verifyBeforeUpdateEmail(newEmail);
        if (!mounted) return;
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Verification email sent to the new email.')),
        );
      } catch (e) {
        if (!mounted) return;
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Email update failed: ')),
        );
      }
    }
  }

